// @vitest-environment happy-dom
import { act, createElement } from "react";
import { afterEach, expect, it, vi } from "vitest";
import { TaskListPane } from "../../../src/components/task-list/TaskListPane";
import { useViewTasks } from "../../../src/hooks/useViewTasks";
import { createDefaultPreferences, createDefaultWorkspace, createTab } from "../../../src/models";
import { useTaskListStore } from "../../../src/state/task-list-store";
import { usePreferencesStore } from "../../../src/state/preferences-store";
import { useWorkspaceStore } from "../../../src/state/workspace-store";
import { taskKey } from "../../../src/utils";
import { makeTask } from "../../helpers/task";
import { mount, type Mounted } from "../../helpers/react-dom";
let host: Mounted | undefined;
let scrollTop = 0;
let rowHeight = 30;
const callbacks = new Set<ResizeObserverCallback>();
afterEach(async () => { await host?.unmount(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
function Pane() { return createElement(TaskListPane, { filePath: "/a", isUnifiedView: false, view: useViewTasks("/a", false), onNewTask: () => {} }); }
it("bounds mounted active rows, measures heights, pins the editor and mounts keyboard targets", async () => {
  vi.stubGlobal("ResizeObserver", class { constructor(readonly callback: ResizeObserverCallback) { callbacks.add(callback); } observe() {} unobserve() {} disconnect() { callbacks.delete(this.callback); } });
  vi.spyOn(HTMLElement.prototype, "clientHeight", "get").mockReturnValue(300);
  vi.spyOn(HTMLElement.prototype, "getBoundingClientRect").mockImplementation(function (this: HTMLElement) {
    const rowsBody = this.parentElement?.hasAttribute("data-group");
    const height = this.getAttribute("role") === "option" ? rowHeight : 300;
    return { top: rowsBody ? 32 - scrollTop : 0, bottom: height, height, width: 300, left: 0, right: 300, x: 0, y: 0, toJSON() {} };
  });
  const scrolled = vi.spyOn(HTMLElement.prototype, "scrollIntoView").mockImplementation(() => {});
  usePreferencesStore.setState({ preferences: createDefaultPreferences() });
  useWorkspaceStore.setState({ workspace: { ...createDefaultWorkspace("Test"), openTabs: [createTab("/a", "A")] } });
  const tasks = Array.from({ length: 10_000 }, (_, i) => makeTask({ id: String(i), title: `Task ${i}` }));
  useTaskListStore.setState({ files: { "/a": { data: { id: "list", tasks } } }, selectedKeys: new Set(), fileLoadErrors: {}, fileDiskErrors: {} });
  host = await mount(createElement(Pane));
  const options = () => [...document.querySelectorAll<HTMLElement>('[role="option"]')];
  expect(options().length).toBeLessThan(100);
  expect(document.querySelector('[data-group="Default"]')?.textContent).toContain("10,000");
  const first = options()[0];
  await act(async () => first.dispatchEvent(new MouseEvent("dblclick", { bubbles: true })));
  const editor = first.querySelector("input");
  expect(editor).not.toBeNull();
  const scroller = document.querySelector<HTMLElement>('[class*="scroll-pt-"]')!;
  await act(async () => { scrollTop = 150_000; scroller.scrollTop = scrollTop; scroller.dispatchEvent(new Event("scroll")); });
  expect(editor!.isConnected).toBe(true);
  expect(options().length).toBeLessThan(100);
  expect(options().map((node) => node.textContent)).toContain("Task 5000");
  const before = options().length;
  await act(async () => { rowHeight = 60; for (const callback of [...callbacks]) callback([], {} as ResizeObserver); });
  expect(options().length).toBeLessThanOrEqual(before);
  await act(async () => editor!.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true, cancelable: true })));
  const list = document.querySelector<HTMLElement>('[role="listbox"]')!;
  await act(async () => list.dispatchEvent(new KeyboardEvent("keydown", { key: "End", bubbles: true, cancelable: true })));
  expect(useTaskListStore.getState().selectedKeys).toEqual(new Set([taskKey("/a", "9999")]));
  const target = document.getElementById(list.getAttribute("aria-activedescendant")!);
  expect(target?.textContent).toContain("Task 9999");
  expect(target?.getAttribute("aria-posinset")).toBe("10000");
  expect(target?.getAttribute("aria-setsize")).toBe("10000");
  expect(scrolled.mock.instances).toContain(target);
  expect(options().length).toBeLessThan(100);
});
